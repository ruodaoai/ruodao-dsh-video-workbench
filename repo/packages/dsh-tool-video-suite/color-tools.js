/**
 * Colour tools: built-in 3D LUTs (programmatically generated 17³ .cube files), FFmpeg `lut3d` grading with an
 * intensity mix, and waveform / vectorscope / histogram scope renders for QA.
 */
import { copyFileSync, existsSync, linkSync, lstatSync, mkdirSync, readFileSync, renameSync, statSync, unlinkSync, writeFileSync } from 'node:fs'
import { basename, dirname, extname, isAbsolute, join, posix, relative, resolve, win32 } from 'node:path'
import { fileURLToPath } from 'node:url'
import { REPO_ROOT, resolveBinaries, runCommandRedirected } from '../shared/index.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
export const BUILTIN_LUT_DIR = join(__dirname, 'luts')
export const LUT_CUBE_SIZE = 17

/** A client-input error the REST layer may show as-is: HTTP `status` + stable `code` (`expose` marks it safe). */
function colorInputError(message, status = 400, code = 'INVALID_INPUT') {
  const err = new Error(message)
  err.status = status
  err.code = code
  err.expose = true
  return err
}

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v)
const smooth = (e0, e1, x) => {
  const t = clamp01((x - e0) / (e1 - e0))
  return t * t * (3 - 2 * t)
}
const luma709 = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b
// Symmetric S-curve around 0.5 (k = contrast amount); endpoints stay fixed
const sCurve = (x, k) => clamp01(x - (k * Math.sin(2 * Math.PI * x)) / (2 * Math.PI))
const mixc = (a, b, t) => a + (b - a) * t

/** Colour transforms in gamma-encoded RGB (0..1). */
const LUT_TRANSFORMS = {
  'teal-orange': ([r, g, b]) => {
    const y = luma709(r, g, b)
    const hi = smooth(0.35, 1.0, y)
    const sh = 1 - smooth(0.0, 0.55, y)
    let R = r + 0.075 * hi - 0.055 * sh
    let G = g + 0.012 * hi + 0.022 * sh
    let B = b - 0.075 * hi + 0.065 * sh
    const y2 = luma709(R, G, B)
    R = mixc(y2, R, 1.12)
    G = mixc(y2, G, 1.12)
    B = mixc(y2, B, 1.12)
    return [sCurve(clamp01(R), 0.14), sCurve(clamp01(G), 0.14), sCurve(clamp01(B), 0.14)]
  },
  'warm-film': ([r, g, b]) => {
    let R = r * 1.045 + 0.01
    let G = g * 1.0 + 0.004
    let B = b * 0.9 - 0.004
    const y = luma709(R, G, B)
    R = mixc(y, R, 0.9)
    G = mixc(y, G, 0.9)
    B = mixc(y, B, 0.9)
    // Film fade: lifted blacks, soft highlight roll-off
    const fade = (x) => 0.045 + 0.92 * (1 - Math.pow(1 - clamp01(x), 1.18))
    return [clamp01(fade(sCurve(clamp01(R), 0.08))), clamp01(fade(sCurve(clamp01(G), 0.08))), clamp01(fade(sCurve(clamp01(B), 0.08)))]
  },
  'bleach-bypass': ([r, g, b]) => {
    const y = luma709(r, g, b)
    const desat = [mixc(r, y, 0.58), mixc(g, y, 0.58), mixc(b, y, 0.58)]
    const yc = sCurve(y, 0.3)
    return desat.map((c, i) => {
      const contrasted = sCurve(clamp01(c + (yc - y)), 0.22)
      return clamp01(i === 2 ? contrasted * 1.02 : i === 0 ? contrasted * 0.99 : contrasted)
    })
  },
  'mono-contrast': ([r, g, b]) => {
    const y = sCurve(sCurve(luma709(r, g, b), 0.22), 0.12)
    return [clamp01(y * 1.01), clamp01(y), clamp01(y * 0.985)]
  },
  'night-cool': ([r, g, b]) => {
    const y = luma709(r, g, b)
    let R = mixc(y, r, 0.62) * 0.78
    let G = mixc(y, g, 0.62) * 0.9
    let B = mixc(y, b, 0.62) * 1.04 + 0.03 * (1 - y)
    const dark = (x) => Math.pow(clamp01(x), 1.22) * 0.86
    return [clamp01(dark(R)), clamp01(dark(G)), clamp01(dark(B))]
  },
}

export const BUILTIN_LUTS = Object.freeze([
  { id: 'teal-orange', label: '青橙电影 (Teal & Orange)', description: '阴影偏青、高光偏橙，适合电影感/动作片' },
  { id: 'warm-film', label: '暖调胶片 (Warm Film)', description: '暖白平衡 + 黑位轻抬 + 柔和高光，复古胶片质感' },
  { id: 'bleach-bypass', label: '漂白旁路 (Bleach Bypass)', description: '低饱和高反差，战争/史诗/冷峻题材' },
  { id: 'mono-contrast', label: '黑白高反差 (Mono Contrast)', description: 'Rec.709 亮度黑白 + S 曲线' },
  { id: 'night-cool', label: '冷调夜景 (Night Cool)', description: '日转夜：压暗 + 冷蓝 + 降饱和' },
])

export function buildCubeLut(id, size = LUT_CUBE_SIZE) {
  const fn = LUT_TRANSFORMS[id]
  if (!fn) throw new Error(`未知内置 LUT: ${id}`)
  const meta = BUILTIN_LUTS.find((l) => l.id === id)
  const lines = [
    `TITLE "DSH ${meta?.label || id}"`,
    '# Generated by DSH Video Workbench (dsh-tool-video-suite/color-tools.js)',
    `LUT_3D_SIZE ${size}`,
    'DOMAIN_MIN 0.0 0.0 0.0',
    'DOMAIN_MAX 1.0 1.0 1.0',
  ]
  const n = size - 1
  // .cube order: red changes fastest, then green, then blue
  for (let bi = 0; bi < size; bi++) {
    for (let gi = 0; gi < size; gi++) {
      for (let ri = 0; ri < size; ri++) {
        const out = fn([ri / n, gi / n, bi / n]).map((v) => clamp01(Number.isFinite(v) ? v : 0))
        lines.push(out.map((v) => v.toFixed(6)).join(' '))
      }
    }
  }
  return lines.join('\n') + '\n'
}

/** Write any missing built-in LUTs into `luts/` (or rewrite all with force). */
export function ensureBuiltinLuts({ force = false, dir = BUILTIN_LUT_DIR } = {}) {
  mkdirSync(dir, { recursive: true })
  const written = []
  for (const l of BUILTIN_LUTS) {
    const p = join(dir, `${l.id}.cube`)
    if (force || !existsSync(p)) {
      writeFileSync(p, buildCubeLut(l.id), 'utf8')
      written.push(p)
    }
  }
  return { dir, written, luts: BUILTIN_LUTS.map((l) => ({ ...l, path: join(dir, `${l.id}.cube`) })) }
}

export function listColorLuts() {
  return ensureBuiltinLuts().luts
}

const LUT_EXTS = new Set(['.cube', '.3dl', '.dat', '.m3d', '.csp'])

/** Resolve a built-in LUT id or a user LUT path (absolute or relative to the project). */
export function resolveLutFile(lut, projectDir = '') {
  const key = String(lut || '').trim()
  if (!key) throw colorInputError('lut 不能为空（内置: ' + BUILTIN_LUTS.map((l) => l.id).join(' / ') + '，或 .cube 文件路径）')
  const builtin = BUILTIN_LUTS.find((l) => l.id === key.toLowerCase() || l.id === key.toLowerCase().replace(/\.cube$/, ''))
  if (builtin) {
    ensureBuiltinLuts()
    return { id: builtin.id, path: join(BUILTIN_LUT_DIR, `${builtin.id}.cube`), builtin: true }
  }
  const abs = isAbsolute(key) ? key : resolve(projectDir || REPO_ROOT, key)
  if (!existsSync(abs) || !statSync(abs).isFile()) throw colorInputError(`LUT 文件不存在: ${abs}`, 404, 'LUT_NOT_FOUND')
  if (!LUT_EXTS.has(extname(abs).toLowerCase())) throw colorInputError(`不支持的 LUT 格式 ${extname(abs)}（支持 .cube/.3dl/.dat/.m3d/.csp）`)
  return { id: basename(abs).replace(/\.[^.]+$/, ''), path: abs, builtin: false }
}

async function probeVideo(file) {
  const { ffprobe } = resolveBinaries()
  const res = await runCommandRedirected(
    ffprobe,
    ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height,pix_fmt,color_space,color_range,duration:format=duration', '-of', 'json', file],
    { timeoutMs: 30_000 },
  )
  try {
    const j = JSON.parse(res.stdout || '{}')
    return { ...(j.streams?.[0] || {}), formatDuration: Number(j.format?.duration || 0) }
  } catch {
    return {}
  }
}

/** Source YUV interpretation so grading round-trips without a colour shift. */
export function resolveSourceColor(info = {}) {
  const fullRange = /^yuvj/.test(String(info.pix_fmt || '')) || info.color_range === 'pc'
  const cs = String(info.color_space || '').toLowerCase()
  const matrix = cs === 'bt709' ? 'bt709' : cs === 'bt470bg' || cs === 'smpte170m' || cs === 'bt601' ? 'bt601' : Number(info.height) >= 720 ? 'bt709' : 'bt601'
  return { fullRange, matrix }
}

/**
 * Grade a video with a 3D LUT. `intensity` 0–1 mixes graded and original (split + lut3d + blend) in planar RGB.
 * Output: H.264 yuv420p, BT.709 tagged, audio stream-copied.
 *
 * Trusted callers only (e.g. delivery-export with its own `output/export/` path): `outputPath` is used as given and an
 * existing file there is replaced. Request / agent input must go through `applyProjectColorLut`, which writes only
 * inside `<project>/output/` and never replaces an existing file unless `overwrite: true`.
 */
export async function applyColorLut({ projectDir, mp4Path, lut, intensity = 1, outputPath, crf = 18, signal } = {}) {
  const absDir = projectDir ? (isAbsolute(projectDir) ? resolve(projectDir) : resolve(REPO_ROOT, projectDir)) : ''
  const src = mp4Path ? resolve(absDir || REPO_ROOT, mp4Path) : join(absDir, 'output', 'final.mp4')
  if (!existsSync(src)) throw colorInputError(`待调色视频不存在: ${src}`, 404, 'SOURCE_NOT_FOUND')
  const lutInfo = resolveLutFile(lut, absDir)
  const k = Math.max(0, Math.min(1, Number(intensity)))
  if (!Number.isFinite(k)) throw colorInputError('intensity 必须是 0–1 之间的数字')
  const out = outputPath
    ? resolve(absDir || REPO_ROOT, outputPath)
    : join(dirname(src), `${basename(src).replace(/\.mp4$/i, '')}.graded-${lutInfo.id.replace(/[^\w.-]+/g, '_')}.mp4`)
  if (resolve(out) === resolve(src)) throw colorInputError('outputPath 不能覆盖源视频')
  mkdirSync(dirname(out), { recursive: true })

  // lut3d's file= option lives inside the filtergraph; run FFmpeg next to a safely named copy instead of escaping paths
  const workDir = join(REPO_ROOT, '.tmp')
  mkdirSync(workDir, { recursive: true })
  const lutName = `lut-${Date.now()}-${Math.random().toString(36).slice(2, 6)}${extname(lutInfo.path).toLowerCase()}`
  copyFileSync(lutInfo.path, join(workDir, lutName))

  const info = await probeVideo(src)
  const { fullRange, matrix } = resolveSourceColor(info)
  const inRange = fullRange ? 'pc' : 'tv'
  const toRgb = `scale=in_color_matrix=${matrix}:in_range=${inRange}:out_range=pc,format=gbrp`
  const toYuv = 'scale=out_color_matrix=bt709:out_range=tv,format=yuv420p'
  const graph =
    k >= 0.999
      ? `[0:v]${toRgb},lut3d=file=${lutName}:interp=tetrahedral,${toYuv}[v]`
      : k <= 0.001
        ? `[0:v]${toRgb},${toYuv}[v]`
        : `[0:v]${toRgb},split=2[orig][tograde];[tograde]lut3d=file=${lutName}:interp=tetrahedral[graded];[graded][orig]blend=all_mode=normal:all_opacity=${k.toFixed(3)},${toYuv}[v]`
  const durSec = Number(info.duration || info.formatDuration || 60)
  try {
    const res = await runCommandRedirected(
      resolveBinaries().ffmpeg,
      [
        '-y', '-hide_banner', '-v', 'error',
        '-i', src,
        '-filter_complex', graph,
        '-map', '[v]', '-map', '0:a?',
        '-c:v', 'libx264', '-preset', 'medium', '-crf', String(Math.max(10, Math.min(30, Number(crf) || 18))),
        '-pix_fmt', 'yuv420p',
        '-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'bt709', '-color_range', 'tv',
        '-c:a', 'copy',
        '-movflags', '+faststart',
        out,
      ],
      { cwd: workDir, timeoutMs: Math.max(180_000, Math.round(durSec * 6000)), signal },
    )
    if (res.code !== 0 || !existsSync(out)) throw new Error(`LUT 调色失败: ${String(res.stderr || '').slice(-500)}`)
  } finally {
    try { unlinkSync(join(workDir, lutName)) } catch {}
  }
  return {
    ok: true,
    sourcePath: src,
    outputPath: out,
    lut: lutInfo.id,
    lutPath: lutInfo.path,
    builtin: lutInfo.builtin,
    intensity: Number(k.toFixed(3)),
    sourceColor: { matrix, range: inRange },
    fileSizeBytes: statSync(out).size,
  }
}

const GRADED_OUTPUT_EXTS = new Set(['.mp4', '.m4v', '.mov'])
const WIN_RESERVED_NAME = /^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)/i
const toPosix = (p) => String(p).split(/[\\/]+/).join('/')

/** True when `a` and `b` are the same file (volume + file id; a path match — case-insensitive on Windows — otherwise). */
function isSameFile(a, b) {
  try {
    const sa = statSync(a, { bigint: true })
    const sb = statSync(b, { bigint: true })
    if (sa.ino && sb.ino) return sa.dev === sb.dev && sa.ino === sb.ino
  } catch {}
  const norm = (p) => (process.platform === 'win32' ? resolve(p).toLowerCase() : resolve(p))
  return norm(a) === norm(b)
}

/** Refuse a symlink / junction anywhere from `<root>/<first segment>` down to `target` (existing components only). */
function assertNoLinkBelow(root, target) {
  let cur = root
  for (const seg of relative(root, target).split(/[\\/]+/).filter(Boolean)) {
    cur = join(cur, seg)
    let st
    try {
      st = lstatSync(cur)
    } catch {
      return // not created yet → nothing below it exists either
    }
    if (st.isSymbolicLink()) {
      throw colorInputError(`输出路径中的「${toPosix(relative(root, cur))}」是符号链接 / 联接 (junction)，为安全起见不写入调色结果`, 409, 'OUTPUT_PATH_LINK')
    }
  }
}

/** Validate a caller-supplied `outputPath` → path segments below `<project>/output/` (a leading `output/` is accepted). */
function parseGradedOutputPath(outputPath) {
  const raw = String(outputPath).trim()
  const bad = (why) => colorInputError(`outputPath 无效：${why}（调色结果只能写入工程 output/ 目录内，例如 "graded/final-teal.mp4"）`, 400, 'INVALID_OUTPUT_PATH')
  if (!raw || raw.length > 240 || raw.includes('\0')) throw bad('为空、过长或含非法字符')
  if (posix.isAbsolute(raw) || win32.isAbsolute(raw) || /^[A-Za-z]:/.test(raw)) throw bad('不支持绝对路径、盘符路径或 UNC 网络路径')
  const parts = raw.split(/[\\/]+/).filter((p) => p && p !== '.')
  if (parts.includes('..')) throw bad('不能包含 ..')
  for (const p of parts) {
    if (/[<>:"|?*\x00-\x1f]/.test(p) || /[. ]$/.test(p) || WIN_RESERVED_NAME.test(p)) throw bad(`文件或目录名「${p}」不可用`)
  }
  if (parts.length > 1 && parts[0].toLowerCase() === 'output') parts.shift()
  if (parts.length === 0 || !GRADED_OUTPUT_EXTS.has(extname(parts[parts.length - 1]).toLowerCase())) throw bad('需为 .mp4 / .mov / .m4v 视频文件')
  return parts
}

/**
 * Where a graded copy for request / agent input goes: always a file inside `<project>/output/`.
 * - `outputPath` given: a path relative to `<project>/output/` (a leading `output/` is accepted); absolute, drive, UNC,
 *   `..` and symlink / junction paths are rejected (400 / 409), and an existing file there is refused (409
 *   `OUTPUT_EXISTS`) unless `overwrite === true`.
 * - no `outputPath`: `output/<source>.graded-<lut>.mp4`; when that already exists the name moves on to `-2`, `-3` …
 *   (an earlier grade is replaced only with `overwrite === true`).
 * The source video is never a valid target.
 */
export function resolveGradedOutputPath({ projectDir, sourcePath = '', lutId = 'lut', outputPath, overwrite = false } = {}) {
  const absDir = resolve(String(projectDir || ''))
  const outputDir = join(absDir, 'output')
  const explicit = outputPath !== undefined && outputPath !== null && String(outputPath).trim() !== ''
  let target
  if (explicit) {
    target = join(outputDir, ...parseGradedOutputPath(outputPath))
  } else {
    const src = String(sourcePath || '')
    const stem = (basename(src, extname(src)) || 'video').replace(/[<>:"|?*\x00-\x1f]+/g, '_').slice(0, 120)
    const tag = String(lutId || 'lut').replace(/[^\w.-]+/g, '_')
    target = join(outputDir, `${stem}.graded-${tag}.mp4`)
    for (let n = 2; overwrite !== true && existsSync(target); n++) {
      target = join(outputDir, `${stem}.graded-${tag}-${n < 1000 ? n : `${Date.now()}-${n}`}.mp4`)
    }
  }
  const rel = relative(outputDir, target)
  if (!rel || rel.startsWith('..') || isAbsolute(rel)) throw colorInputError('outputPath 必须位于工程 output/ 目录内', 400, 'INVALID_OUTPUT_PATH')
  const relPath = `output/${toPosix(rel)}`
  assertNoLinkBelow(absDir, target)
  let existing = null
  try {
    existing = lstatSync(target)
  } catch {}
  if (existing && !existing.isFile()) throw colorInputError(`输出路径已被目录或特殊文件占用: ${relPath}`, 409, 'OUTPUT_EXISTS')
  if (sourcePath && isSameFile(target, sourcePath)) throw colorInputError('outputPath 不能覆盖源视频')
  if (existing && overwrite !== true) {
    throw colorInputError(`输出文件已存在: ${relPath}（不会覆盖已有文件；如确需替换请传 overwrite: true）`, 409, 'OUTPUT_EXISTS')
  }
  return { outputPath: target, outputDir, relPath, replacesExisting: Boolean(existing) }
}

/**
 * `applyColorLut` for request / agent input (REST `POST color-lut`, MCP `apply_color_lut`): `projectDir` must be an
 * existing video project (folder with script.json); the graded copy is written only inside `<project>/output/` (see
 * `resolveGradedOutputPath`) and never replaces an existing file unless `overwrite: true`. FFmpeg writes a hidden
 * temporary file next to the target first, so a failed grade never destroys an earlier file. Errors carry
 * `status` / `code` / `expose` for the REST layer.
 */
export async function applyProjectColorLut({ projectDir, mp4Path, lut, intensity = 1, outputPath, overwrite = false, crf = 18, signal } = {}) {
  const raw = typeof projectDir === 'string' ? projectDir.trim() : ''
  if (!raw || raw.includes('\0')) throw colorInputError('projectDir is required', 400, 'BAD_REQUEST')
  const absDir = isAbsolute(raw) ? resolve(raw) : resolve(REPO_ROOT, raw)
  let dirStat = null
  try {
    dirStat = statSync(absDir)
  } catch {}
  if (!dirStat?.isDirectory()) throw colorInputError(`视频工程目录不存在: ${absDir}`, 404, 'PROJECT_NOT_FOUND')
  if (!existsSync(join(absDir, 'script.json'))) throw colorInputError(`该目录不是视频工程（缺少 script.json）: ${absDir}`, 404, 'PROJECT_NOT_FOUND')
  const src = mp4Path ? resolve(absDir, String(mp4Path)) : join(absDir, 'output', 'final.mp4')
  let srcStat = null
  try {
    srcStat = statSync(src)
  } catch {}
  if (!srcStat?.isFile()) throw colorInputError(`待调色视频不存在: ${src}`, 404, 'SOURCE_NOT_FOUND')
  const lutInfo = resolveLutFile(lut, absDir)
  const replace = overwrite === true
  const target = resolveGradedOutputPath({ projectDir: absDir, sourcePath: src, lutId: lutInfo.id, outputPath, overwrite: replace })
  mkdirSync(dirname(target.outputPath), { recursive: true })
  const ext = extname(target.outputPath)
  const tmp = join(dirname(target.outputPath), `.${basename(target.outputPath, ext)}.partial-${process.pid}-${Date.now().toString(36)}${ext}`)
  try {
    const res = await applyColorLut({ projectDir: absDir, mp4Path: src, lut, intensity, outputPath: tmp, crf, signal })
    if (replace) {
      renameSync(tmp, target.outputPath)
    } else {
      try {
        linkSync(tmp, target.outputPath) // no-clobber: fails when the file appeared in the meantime
      } catch (err) {
        if (err?.code === 'EEXIST' || existsSync(target.outputPath)) {
          throw colorInputError(`输出文件已存在: ${target.relPath}（不会覆盖已有文件；如确需替换请传 overwrite: true）`, 409, 'OUTPUT_EXISTS')
        }
        renameSync(tmp, target.outputPath) // volume without hard links
      }
    }
    return {
      ...res,
      projectDir: absDir,
      outputPath: target.outputPath,
      outputRelPath: target.relPath,
      replacedExisting: target.replacesExisting,
      fileSizeBytes: statSync(target.outputPath).size,
    }
  } finally {
    try {
      unlinkSync(tmp)
    } catch {}
  }
}

export const SCOPE_KINDS = Object.freeze(['waveform', 'vectorscope', 'histogram'])

/**
 * Render waveform / vectorscope / histogram PNGs (plus the analysed frame) for one timestamp into `output/scopes/`.
 */
export async function renderVideoScopes({ projectDir, mp4Path, timeSec = 0, kinds = SCOPE_KINDS, outDir, signal } = {}) {
  const absDir = projectDir ? (isAbsolute(projectDir) ? resolve(projectDir) : resolve(REPO_ROOT, projectDir)) : ''
  const src = mp4Path ? resolve(absDir || REPO_ROOT, mp4Path) : join(absDir, 'output', 'final.mp4')
  if (!existsSync(src)) throw new Error(`视频不存在: ${src}`)
  const wanted = (Array.isArray(kinds) && kinds.length ? kinds : SCOPE_KINDS).map((k) => String(k).toLowerCase())
  for (const k of wanted) {
    if (!SCOPE_KINDS.includes(k)) throw new Error(`不支持的示波器类型: ${k}（可选 ${SCOPE_KINDS.join(' / ')}）`)
  }
  const info = await probeVideo(src)
  const dur = Number(info.duration || info.formatDuration || 0)
  const t = Math.max(0, Math.min(Number(timeSec) || 0, dur > 0.05 ? dur - 0.04 : 0))
  const dir = outDir ? resolve(absDir || REPO_ROOT, outDir) : join(absDir || dirname(src), 'output', 'scopes')
  mkdirSync(dir, { recursive: true })
  const tag = `${t.toFixed(2).replace('.', '_')}s`
  const branches = ['frame', ...wanted]
  const chains = {
    frame: 'scale=w=960:h=-2',
    waveform: 'scale=w=960:h=-2,format=yuv444p,waveform=mode=column:display=overlay:components=1:intensity=0.12:graticule=green:flags=numbers+dots:scale=digital',
    vectorscope: 'scale=w=960:h=-2,format=yuv444p,vectorscope=mode=color3:intensity=0.12:graticule=green:flags=name',
    histogram: 'scale=w=960:h=-2,format=yuv444p,histogram=display_mode=stack:level_height=160',
  }
  const labels = branches.map((b) => `[s_${b}]`)
  const graph = [`[0:v]split=${branches.length}${labels.join('')}`, ...branches.map((b) => `[s_${b}]${chains[b]}[o_${b}]`)].join(';')
  const files = {}
  const args = ['-y', '-hide_banner', '-v', 'error', '-ss', t.toFixed(3), '-i', src, '-filter_complex', graph]
  for (const b of branches) {
    const p = join(dir, `${b}-${tag}.png`)
    files[b] = p
    args.push('-map', `[o_${b}]`, '-frames:v', '1', '-update', '1', p)
  }
  const res = await runCommandRedirected(resolveBinaries().ffmpeg, args, { timeoutMs: 60_000, signal })
  const missing = branches.filter((b) => !existsSync(files[b]))
  if (res.code !== 0 || missing.length) {
    throw new Error(`示波器渲染失败 (${missing.join(',') || 'ffmpeg'}): ${String(res.stderr || '').slice(-400)}`)
  }
  return { ok: true, sourcePath: src, timeSec: Number(t.toFixed(3)), outDir: dir, files }
}

/** Parse a .cube file header (used by tests and the REST LUT list). */
export function readCubeHeader(path) {
  const head = readFileSync(path, 'utf8').split(/\r?\n/).slice(0, 12)
  const size = Number((head.find((l) => /^LUT_3D_SIZE\s+/i.test(l)) || '').split(/\s+/)[1] || 0)
  const title = (head.find((l) => /^TITLE\s+/i.test(l)) || '').replace(/^TITLE\s+"?|"?$/g, '')
  return { size, title }
}
