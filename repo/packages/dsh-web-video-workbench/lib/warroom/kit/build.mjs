// Build the native panel kit: lib/warroom/kit/src/*.js → lib/warroom/kit.js, src/*.css → lib/warroom/kit.css
// Each JS module is syntax-checked on its own and wrapped in try/catch, so one broken module can never take the
// other panels (or the skin) down. A module that fails the syntax check is left out and the build exits 1.
// usage: node packages/dsh-web-video-workbench/lib/warroom/kit/build.mjs [--check]
import { readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const here = dirname(fileURLToPath(import.meta.url))
const srcDir = join(here, 'src')
const outDir = join(here, '..')
const checkOnly = process.argv.includes('--check')

const files = readdirSync(srcDir).sort()
const jsParts = []
const cssParts = []
const failed = []
for (const f of files) {
  const text = readFileSync(join(srcDir, f), 'utf8').replace(/^﻿/, '')
  if (f.endsWith('.js')) {
    try {
      new vm.Script(text, { filename: f })
    } catch (err) {
      failed.push(`${f}: ${err.message}`)
      continue
    }
    jsParts.push(`/* ---- ${f} ---- */\ntry {\n${text}\n} catch (err) {\n  console.error('[PK] module ${f} failed to load', err)\n}\n`)
  } else if (f.endsWith('.css')) {
    cssParts.push(`/* ---- ${f} ---- */\n${text}\n`)
  }
}
const header = (kind) =>
  `/* DSH Video Workbench · 原生面板内核 (panel kit) ${kind} — GENERATED by kit/build.mjs from kit/src. Do not edit. */\n`
const js = header('kit.js') + jsParts.join('\n')
const css = header('kit.css') + cssParts.join('\n')
try {
  new vm.Script(js, { filename: 'kit.js' })
} catch (err) {
  failed.push(`kit.js (bundle): ${err.message}`)
}
if (!checkOnly) {
  for (const [name, body] of [
    ['kit.js', js],
    ['kit.css', css],
  ]) {
    const tmp = join(outDir, `.${name}.${process.pid}.tmp`)
    writeFileSync(tmp, body)
    renameSync(tmp, join(outDir, name))
  }
}
console.log(`[kit] ${jsParts.length} js modules · ${cssParts.length} css files · kit.js ${(js.length / 1024).toFixed(1)} KB · kit.css ${(css.length / 1024).toFixed(1)} KB${checkOnly ? ' (check only)' : ''}`)
if (failed.length) {
  console.error(`[kit] ${failed.length} module(s) left out:\n  ${failed.join('\n  ')}`)
  process.exit(1)
}
